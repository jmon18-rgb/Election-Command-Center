'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const hist=require('./historical_candidate_strength.js'),{reconcile}=require('./reconcile_house_historical_context.cjs');
const read=n=>JSON.parse(fs.readFileSync('data/'+n+'.json','utf8'));
const ctx=read('candidate_fundamentals_staging'),doc=read('historical_candidate_overperformance_2026');
assert.deepEqual(hist.refreshHouseCandidateContext(ctx,doc,doc),ctx,'Rerunning migration is idempotent');
const corrupt=structuredClone(ctx),house=corrupt.records.find(r=>r.office==='house'&&r.rep.historical_overperformance_provenance);
house.rep.incumbent_last_race_overperformance_points+=1;
assert.throws(()=>hist.refreshHouseCandidateContext(corrupt,doc,doc),'Unreproducible old provenance cannot authorize replacement');
const senate=structuredClone(doc),s=senate.records.find(r=>r.office==='senate'&&r.status==='matched_historic_winner_2020');
s.candidate_signed_raw_excess_margin_points+=1;
assert.throws(()=>hist.refreshHouseCandidateContext(ctx,doc,senate),'House-only migration cannot alter independent Senate facts');
const facts=structuredClone(ctx),r=facts.records.find(r=>r.office==='house'&&r.rep.historical_overperformance_provenance);
r.rep.state_office_experience='independently_curated_test_fact';
const refreshed=hist.refreshHouseCandidateContext(facts,doc,doc);
assert.equal(refreshed.records.find(x=>x.race_code===r.race_code).rep.state_office_experience,'independently_curated_test_fact');
const names=read('house_2024_candidate_results_staging'),history=read('house_history_2024_staging'),geo=read('house_geography_bridge');
const original=structuredClone(names),bad=structuredClone(history);
bad.records.find(r=>r['2024_race_code']==='NY-17').recorded_rep_votes-=16921;
const rejected=reconcile(names,bad,geo).records.find(r=>r.race_code==='NY-17');
assert.equal(rejected.source_votes_match_mit_staging,false,'A source mismatch stays blocked; independent candidate counts are never overwritten');
assert.equal(rejected.rep_votes,197845);assert.deepEqual(names,original);
assert.equal(names.coverage.vote_disagreements,2,'Residual independent-source discrepancies remain explicit');
console.log('Atomic House migration: original provenance, immutable independent facts, Senate isolation, idempotence and source-disagreement gates PASS');
